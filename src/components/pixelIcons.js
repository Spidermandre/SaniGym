// Converte una griglia in un unico tracciato SVG (un quadrato per pixel acceso).
export function pixelPath(rows) {
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") d += `M${x} ${y}h1v1h-1z`;
  });
  return d;
}
